"""Pass / fail criteria - FIXED BEFORE THE FIRST BATCH RUN (2026-10-28).  scripts/run_all.py records the
SHA-256 of this file in results/summary.json so that a later edit would be visible.

Longitudinal scenarios (cut-in, cut-out, decelerating lead), per run, in this order:
  FAIL_COLLISION  bounding boxes touched                         R171 5.3.7.2.5.1 (collision avoidance)
  FAIL_TTC        min TTC to an object in the Ego lane < 1.0 s    project safety-margin criterion
  FAIL_DECEL      500 ms mean achieved deceleration > 5.5 m/s2    Euro NCAP VA 2: ACC <= 5 m/s2 + 10 %
  FAIL_LATERAL    max |lateral offset| > 0.5 m                     project lane-keeping criterion
  PASS_HARSH      safe, but peak deceleration (500 ms) > 3.5 m/s2  R171 5.3.7.2.5.2 "without any harsh braking"
  PASS
  safe = PASS or PASS_HARSH.  The failure boundary is the safe / unsafe border.
Lane centring (curves):
  FAIL_LATERAL    while the function steers: a_y above declared + 0.3 m/s2 for more than 2 s, a_y above the
                  2 s limit (3.3 m/s2), or 0.5 s mean lateral jerk > 5 m/s3 (R171 5.3.7.1.2, 5.3.7.1.2.1);
                  or |d| > 0.5 m / lane departure without a DCA shown before the departure
  BOUNDARY_HANDLED  |d| > 0.5 m or lane departure, but the lateral-limit DCA was shown no later than the lane
                  departure (R171 5.3.7.1.4: continued assistance + optical and acoustic/haptic warning)
  PASS            |d| <= 0.5 m throughout and no lane departure
False braking (non-threatening lateral approach): commanded deceleration >= 1.0 m/s2 while the probe vehicle
was the ACC target, or speed loss >= 3 km/h.
"""
from __future__ import annotations

from . import regulations as R

MIN_TTC_S = 1.0
MAX_DECEL_500MS = R.ENCAP_VA_ACC_DECEL_MAX * (1.0 + R.ENCAP_VA_ACC_DECEL_TOL)   # 5.5 m/s2
MAX_ABS_D_M = 0.5
HARSH_DECEL = 3.5
LAT_SHORT_LIMIT = R.R171_LAT_ACC_MAX_M1 + R.R171_LAT_ACC_TOL                    # 3.3 m/s2 for <= 2 s
LAT_SHORT_S = R.R171_LAT_ACC_SHORT_S
LAT_JERK_MAX = R.R171_LAT_JERK_MAX
FALSE_BRAKE_DECEL = 1.0
FALSE_BRAKE_DV_KPH = 3.0

SAFE = ("PASS", "PASS_HARSH")


def longitudinal_verdict(r) -> str:
    if r.collision:
        return "FAIL_COLLISION"
    if r.min_ttc_s < MIN_TTC_S:
        return "FAIL_TTC"
    if r.peak_decel_500ms > MAX_DECEL_500MS:
        return "FAIL_DECEL"
    if r.max_abs_d > MAX_ABS_D_M:
        return "FAIL_LATERAL"
    if r.peak_decel_500ms > HARSH_DECEL:
        return "PASS_HARSH"
    return "PASS"


def is_safe(verdict: str) -> bool:
    return verdict in SAFE


def lateral_verdict(r) -> str:
    """Lateral accelerations / jerk count only while the function steers (R171: values 'generated by the
    system'); the lane position counts until the driver has taken over."""
    if r.ay_over_sustained_max_s > LAT_SHORT_S or r.peak_ay > LAT_SHORT_LIMIT + 1e-9 or r.peak_jy_500ms > LAT_JERK_MAX:
        return "FAIL_LATERAL"
    if not r.lane_departure and r.t_d05 is None:
        return "PASS"
    dca = r.first("dca_shown:lateral_limit")
    if dca is not None and (r.t_lane_departure is None or dca <= r.t_lane_departure + 1e-9):
        return "BOUNDARY_HANDLED"
    return "FAIL_LATERAL"


def false_brake(r, oid: str = "Adj") -> bool:
    return r.brake_on_object.get(oid, 0.0) >= FALSE_BRAKE_DECEL or (r.v0_kph - r.v_min_kph) >= FALSE_BRAKE_DV_KPH

"""One closed-loop run: world backend (esmini or Python) + object list + DCAS (ACC, lane centring, boundary
monitor, driver-engagement monitor, mode manager) + scripted driver + Ego plant.

Per step (dt = 20 ms):
  1. object truths from the backend; collision and safety metrics against the truth
  2. scripted driver inputs (gaze, eyelid, hands, pedals, torque, buttons)
  3. engagement monitor (copied P7 detectors + R171 escalation) -> requests
  4. object list -> ACC target selection; boundary monitor
  5. mode manager -> which channels the function controls
  6. ACC / lane centring / risk-mitigation profile, or the driver's own control
  7. Ego plant, reported to the backend; backend advances one step
"""
from __future__ import annotations

import copy
import math
from dataclasses import asdict, dataclass, field

from .acc import Acc, HALF_LANE
from .backends import boxes_overlap
from .boundary import BoundaryMonitor
from .driver import DriverScript, ScriptedDriver, manual_lane_keeping
from .engagement import EngagementMonitor
from .lcc import LaneCentering
from .params import BASELINE, DcasConfig
from .perception import Perception
from .road import EGO_LANE, all_roads, lane_center_t
from .scenarios import CURVE_ROAD, Case
from .state_machine import ACTIVE, MRM, OFF, OVERRIDE, STANDBY, TOR, SmInputs, StateMachine
from .vehicle import EGO_FRONT, EGO_WIDTH, EgoVehicle

ROADS = all_roads()
LANE_DEPARTURE_D = HALF_LANE - 1.85 / 2.0      # Ego body edge on the lane boundary line (0.825 m)
DECIMATE = 5                                   # curve preview / boundary preview every 5 steps (100 ms)


@dataclass
class RunResult:
    case_id: str
    family: str
    backend: str
    collision: bool = False
    t_collision: float | None = None
    collided_with: str = ""
    v_rel_impact_kph: float = 0.0
    backend_collision: bool | None = None
    min_ttc_s: float = float("inf")
    min_gap_m: float = float("inf")
    peak_decel: float = 0.0              # achieved
    peak_decel_500ms: float = 0.0        # 500 ms running mean of the achieved deceleration
    peak_decel_cmd: float = 0.0
    peak_jerk: float = 0.0
    max_abs_d: float = 0.0
    lane_departure: bool = False
    t_lane_departure: float | None = None    # first time the Ego body edge is beyond the lane boundary line
    t_d05: float | None = None               # first time |d| > 0.5 m while the function steers
    # lateral quantities GENERATED BY THE SYSTEM (accumulated only while the function steers, R171 5.3.7.1.2)
    peak_ay: float = 0.0
    ay_over_sustained_max_s: float = 0.0     # longest continuous time above declared + 0.3 m/s2
    peak_jy_500ms: float = 0.0               # 0.5 s moving average of lateral jerk
    v0_kph: float = 0.0
    v_min_kph: float = 0.0
    v_end_kph: float = 0.0
    t_selected: float | None = None          # first time the scenario object of interest is in path
    a_kin_at_selection: float | None = None
    brake_on_object: dict = field(default_factory=dict)    # oid -> max commanded deceleration while it was the target
    t_confirmed: dict = field(default_factory=dict)        # oid -> first time the object is a confirmed track
    t_brake: float | None = None             # first commanded deceleration <= -0.5 m/s2 by the function
    selected_objects: list = field(default_factory=list)
    states: str = ""
    transitions: list = field(default_factory=list)
    events: list = field(default_factory=list)               # (t, name)
    refusals: list = field(default_factory=list)
    lockout: bool = False
    t_standstill: float | None = None
    end_reason: str = ""
    t_end: float = 0.0
    series: dict | None = None

    def first(self, name: str) -> float | None:
        for t, n in self.events:
            if n == name:
                return t
        return None


def _road_for(case: Case):
    return ROADS[CURVE_ROAD[case.family]] if case.family in CURVE_ROAD else ROADS["highway_straight"]


def _in(t: float, seg) -> bool:
    return seg is not None and seg[0] <= t < seg[1]


def run_case(case: Case, backend, cfg: DcasConfig = BASELINE, record: bool = False, log_stem: str | None = None,
             seed: int = 0, object_of_interest: str | None = None) -> RunResult:
    backend.start(case.family, case.params, cfg.dt, log_stem)
    try:
        return _loop(case, backend, cfg, record, seed, object_of_interest)
    finally:
        backend.close()


def _loop(case: Case, backend, cfg: DcasConfig, record: bool, seed: int, ooi: str | None) -> RunResult:
    dt = cfg.dt
    p, meta = case.params, case.meta
    road = _road_for(case)
    t_lane = lane_center_t(EGO_LANE)
    v0 = float(p["EgoSpeed"])
    ego = EgoVehicle(cfg, road, float(p["EgoStartS"]), v0)
    per = Perception(cfg, seed)
    acc = Acc(cfg, road, t_lane)
    acc.gap_idx = meta.get("gap_idx", cfg.gap_default_idx)
    lcc = LaneCentering(cfg, road, t_lane)
    lcc.reset(ego.ay)
    bnd = BoundaryMonitor(cfg, road, t_lane)
    eng = EngagementMonitor(cfg)
    sm = StateMachine(cfg, OFF)
    script = meta.get("script") or DriverScript()
    drv = ScriptedDriver(script, dt, cfg.steer_override_nm)
    v_set = meta.get("v_set_kph", meta.get("v_vut_kph", v0 * 3.6)) / 3.6
    curve_on = meta.get("csa", True)
    markings_lost = meta.get("markings_lost")
    failure_at = meta.get("failure_at")
    sim_end = float(p["SimEndTime"])
    ooi = ooi or {"CutIn": "Target", "LatProbe": "Adj", "CutOut": "Stat", "LeadBrake": "Lead"}.get(case.family)

    res = RunResult(case.case_id, case.family, backend.name, v0_kph=v0 * 3.6, v_min_kph=v0 * 3.6)
    ser = {k: [] for k in ("t", "s", "d", "v", "a", "a_cmd", "ay", "state", "level", "target", "gap", "ttc",
                           "vis_s", "hands_off_s", "obj_t")} if record else None
    acc_cmd = 0.0
    acc_sys = 0.0
    prev_long_on = False
    a_hist: list[float] = []
    ay_hist: list[float] = []
    over_run = 0.0
    a_prev = 0.0
    v_tor = None
    t_mrm = None
    v_curve_cache = None
    prev_state = sm.state
    gap_add_until = -1.0
    tail_end = None
    k = 0
    while True:
        t = k * dt
        x = ego.x
        objs = backend.objects()
        # ---------------------------------------------------------------- truth metrics
        t_ego = t_lane + x.d
        for o in objs:
            if boxes_overlap(x.s, t_ego, o) and not res.collision:
                res.collision, res.t_collision, res.collided_with = True, round(t, 3), o.oid
                res.v_rel_impact_kph = max(0.0, (x.v - o.v) * 3.6)
                tail_end = t + 0.5
            # TTC / gap only against objects that overlap the Ego body laterally (they would be hit)
            gap = (o.s + o.cx - o.length / 2.0) - (x.s + EGO_FRONT)
            if abs(o.t - t_ego) < (EGO_WIDTH + o.width) / 2.0 and gap > 0.0:
                res.min_gap_m = min(res.min_gap_m, gap)
                closing = x.v - o.v
                if closing > 0.1:
                    res.min_ttc_s = min(res.min_ttc_s, gap / closing)
        # ---------------------------------------------------------------- driver and engagement
        di = drv.inputs(t)
        monitoring = sm.state in (ACTIVE, OVERRIDE, TOR)
        eo = eng.step(t, x.v * 3.6, di.gaze, di.eyelid, di.hands_on, di.camera_ok, True, True, monitoring)
        for e in eo.events:
            res.events.append((round(t, 3), e))
        if eo.microsleep_event:
            gap_add_until = t + cfg.microsleep_gap_hold_s
            res.events.append((round(t, 3), f"time_gap+{cfg.microsleep_gap_add_s:g}s"))
        acc.gap_add_s = cfg.microsleep_gap_add_s if t < gap_add_until else 0.0
        # ---------------------------------------------------------------- perception and boundaries
        tracks = per.step(k, x.s, x.d, x.v, objs)
        for tr in tracks:
            if tr.oid not in res.t_confirmed:
                res.t_confirmed[tr.oid] = round(t, 3)
        if k % DECIMATE == 0 or v_curve_cache is None:
            bo = bnd.step(x.v, x.s, x.d, lcc.saturated, not _in(t, markings_lost), eo.dsm_unavailable_long,
                          di.seatbelt, curve_on, sm.state in (ACTIVE, TOR, MRM))
            v_curve_cache = acc.curve_speed(x.s, x.d, x.v) if curve_on else float("inf")
            bo_cache = bo
        else:   # cheap re-evaluation of the instantaneous boundaries (markings, lateral, dsm, seat belt)
            bo = _instant_boundaries(bnd, cfg, x, lcc, markings_lost, t, eo, di, sm, bo_cache)
        if eo.lockout:            # R171 5.5.4.2.8.1: disable the system -> controllable termination via a DCA
            if not res.lockout:
                res.lockout = True
                res.events.append((round(t, 3), "lockout"))
            bo = copy.copy(bo)
            bo.within = False
            bo.reason = "+".join(r for r in (bo.reason, "lockout") if r)
        if bo.approaching and not any(n == "boundary_approaching" for _, n in res.events[-50:]):
            res.events.append((round(t, 3), "boundary_approaching"))
        failure = failure_at is not None and t >= failure_at
        accel_override = di.accel_demand is not None and di.accel_demand > acc_sys + 0.05
        si = SmInputs(t=t, v_kph=x.v * 3.6, main_switch=di.main_switch, set_pressed=di.set_pressed,
                      cancel_pressed=di.cancel_pressed, brake_pedal=di.brake_pedal, accel_override=accel_override,
                      steer_torque_nm=di.steer_torque_nm, hands_on=di.hands_on, seatbelt=di.seatbelt, failure=failure,
                      dca_request=eo.dca_request, unavailable=eo.unavailable, dsm_ok=eo.dsm_ok, lockout=eo.lockout,
                      within_boundaries=bo.within, boundary_reason=bo.reason, standstill=x.v < 0.05)
        so = sm.step(si)
        for e in so.events:
            res.events.append((round(t, 3), e))
        if "driver_took_over" in so.events:
            eng.driver_took_over(t)
            drv.confirm_takeover()
        if so.state == ACTIVE and prev_state in (OFF, STANDBY) and not any(n == "headway_info" for _, n in res.events):
            if acc.time_gap < 2.0:      # R171 5.3.7.5.1.1.2: inform at first activation if the setting is < 2 s
                res.events.append((round(t, 3), "headway_info"))
        if so.state == MRM and prev_state != MRM:
            t_mrm = t
            eng.unavailability_started(t)
            res.events.append((round(t, 3), "mrm_start"))
        if so.state == TOR and prev_state != TOR:
            v_tor = x.v
            res.events.append((round(t, 3), f"dca_shown:{sm.tor_cause}"))
        level = eo.level or ("DCA" if so.state == TOR else "")
        drv.notify(t, level, so.state)
        # ---------------------------------------------------------------- longitudinal
        engaged = so.state in (ACTIVE, OVERRIDE, TOR) or (so.state == MRM and x.v >= 0.05)
        if engaged:
            a_min = None
            vs = v_set
            if so.state == TOR:
                vs = min(v_set, v_tor if v_tor is not None else x.v)
            if so.state == MRM:
                a_min = max(-cfg.mrm_decel, -cfg.mrm_jerk * (t - t_mrm))
            if so.longitudinal_on and not prev_long_on:
                acc.reset_command(x.a)                 # bumpless take-over of longitudinal control
            ao = _acc_step(acc, tracks, x, vs, curve_on, a_min, v_curve_cache)
            acc_sys = ao.a_des                         # system demand, also during an accelerator override
        if engaged and so.longitudinal_on:
            a_req = ao.a_cmd
            acc_cmd = ao.a_cmd
            if res.t_brake is None and ao.a_cmd <= -0.5:
                res.t_brake = round(t, 3)
            if ao.target:
                res.brake_on_object[ao.target] = max(res.brake_on_object.get(ao.target, 0.0), -min(0.0, ao.a_cmd))
            for oid in ao.targets:
                if oid not in res.selected_objects:
                    res.selected_objects.append(oid)
                if oid == ooi and res.t_selected is None:
                    res.t_selected = round(t, 3)
                    trk = next((tr for tr in tracks if tr.oid == oid), None)
                    if trk is not None and trk.v_rel < 0:
                        res.a_kin_at_selection = trk.v_rel ** 2 / (2.0 * max(trk.gap, 0.1))
                    else:
                        res.a_kin_at_selection = 0.0
        elif so.state == MRM:
            a_req = -1.0                     # standstill hold
            acc_cmd = a_req
            if res.t_standstill is None:
                res.t_standstill = round(t, 3)
                tail_end = t + 3.0
        else:
            if di.brake_pedal:
                a_req = -di.brake_decel
            elif di.accel_demand is not None:
                a_req = di.accel_demand
            else:
                a_req = 0.0
            acc_cmd = a_req
            acc.reset_command(x.a)
        if so.state == OVERRIDE and "accel" in so.override_kind and di.accel_demand is not None:
            a_req = di.accel_demand
        # ---------------------------------------------------------------- lateral
        if so.lateral_on:
            if prev_state not in (ACTIVE, OVERRIDE, TOR, MRM):
                lcc.reset(ego.ay)
            kappa_req = lcc.step(x.s, x.d, x.psi, x.v)
        elif di.hands_on:
            target_d = 0.4 * math.copysign(1.0, di.steer_torque_nm) if abs(di.steer_torque_nm) > cfg.steer_override_nm else 0.0
            kappa_req = manual_lane_keeping(x.d - target_d, x.psi, x.v, road.lane_curvature(x.s, t_ego))
            lcc.reset(ego.ay)
        else:
            kappa_req = x.kappa
        prev_state = so.state
        prev_long_on = so.longitudinal_on
        # ---------------------------------------------------------------- metrics
        res.peak_decel = max(res.peak_decel, -x.a)
        res.peak_decel_cmd = max(res.peak_decel_cmd, -acc_cmd)
        res.peak_jerk = max(res.peak_jerk, abs(x.a - a_prev) / dt)
        a_prev = x.a
        a_hist.append(x.a)
        if len(a_hist) > 25:
            a_hist.pop(0)
        res.peak_decel_500ms = max(res.peak_decel_500ms, -sum(a_hist) / len(a_hist))
        res.max_abs_d = max(res.max_abs_d, abs(x.d))
        if abs(x.d) > LANE_DEPARTURE_D and not res.lane_departure:
            res.lane_departure, res.t_lane_departure = True, round(t, 3)
        if so.lateral_on:
            if abs(x.d) > 0.5 and res.t_d05 is None:
                res.t_d05 = round(t, 3)
            res.peak_ay = max(res.peak_ay, abs(ego.ay))
            ay_hist.append(ego.ay)
            if len(ay_hist) > 26:
                ay_hist.pop(0)
            if len(ay_hist) == 26:
                res.peak_jy_500ms = max(res.peak_jy_500ms, abs(ay_hist[-1] - ay_hist[0]) / 0.5)
            over_run = over_run + dt if abs(ego.ay) > cfg.ay_declared + 0.3 + 1e-9 else 0.0
            res.ay_over_sustained_max_s = max(res.ay_over_sustained_max_s, over_run)
        else:
            ay_hist.clear()
            over_run = 0.0
        res.v_min_kph = min(res.v_min_kph, x.v * 3.6)
        if record:
            o = next((o for o in objs if o.oid == ooi), None)
            gapo = (o.s + o.cx - o.length / 2.0) - (x.s + EGO_FRONT) if o else float("nan")
            ttco = gapo / (x.v - o.v) if (o and x.v - o.v > 0.1 and gapo > 0) else float("nan")
            for key, val in (("t", t), ("s", x.s), ("d", x.d), ("v", x.v), ("a", x.a), ("a_cmd", acc_cmd),
                             ("ay", ego.ay), ("state", so.state), ("level", level), ("target", ",".join(acc.in_path)),
                             ("gap", gapo), ("ttc", ttco), ("vis_s", eo.vis_s), ("hands_off_s", eo.hands_off_s),
                             ("obj_t", (o.t - t_lane) if o else float("nan"))):
                ser[key].append(val)
        # ---------------------------------------------------------------- end of run
        if tail_end is not None and t >= tail_end:
            res.end_reason = "collision" if res.collision else "standstill after MRM"
            break
        if t >= sim_end - 1e-9:
            res.end_reason = "scenario end"
            break
        # ---------------------------------------------------------------- plant
        ego.step(a_req, kappa_req)
        backend.advance(dt, ego.x.s, ego.x.d, ego.x.v)
        k += 1
    res.t_end = round(t, 3)
    res.v_end_kph = ego.x.v * 3.6
    res.transitions = list(sm.log)
    res.states = ">".join([OFF] + [b for _, a, b, tid, _d in sm.log if a != b])
    res.refusals = list(sm.refusals)
    res.lockout = eng.lockout
    res.backend_collision = backend.collision if backend.name == "esmini" else None
    res.series = ser
    return res


def _instant_boundaries(bnd, cfg, x, lcc, markings_lost, t, eo, di, sm, cached):
    """Between preview updates: refresh the instantaneous boundaries, keep the cached 'approaching' flag."""
    from .boundary import BoundaryOut, LAT_LIMIT_D_M, SPEED_TOL_KPH
    bnd.lost_n = 0 if not _in(t, markings_lost) else bnd.lost_n + 1
    reasons = []
    if bnd.lost_n * cfg.dt > cfg.lane_marking_lost_s:
        reasons.append("lane_markings")
    if sm.state in (ACTIVE, TOR, MRM) and lcc.saturated and abs(x.d) > LAT_LIMIT_D_M:
        reasons.append("lateral_limit")
    if x.v * 3.6 > cfg.v_max_kph + SPEED_TOL_KPH:
        reasons.append("speed_range")
    if eo.dsm_unavailable_long:
        reasons.append("dsm")
    if not di.seatbelt:
        reasons.append("seatbelt")
    out = BoundaryOut(approaching=cached.approaching, approach_reason=cached.approach_reason)
    if reasons:
        out.within, out.reason = False, "+".join(reasons)
    return out


def _acc_step(acc: Acc, tracks, x, v_set, curve_on, a_min, v_curve):
    """acc.step with the curve-speed limit computed at the decimated rate."""
    out = acc.step(tracks, x.v, x.s, x.d, min(v_set, v_curve), curve_on=False, a_override_min=a_min)
    out.v_curve = v_curve
    return out


def flat(r: RunResult) -> dict:
    d = asdict(r)
    d.pop("series", None)
    d["transitions"] = " ".join(f"{t:.2f}:{a}>{b}({tid}{':' + det if det else ''})" for t, a, b, tid, det in r.transitions)
    d["events"] = " ".join(f"{t:.2f}:{n}" for t, n in r.events)
    d["refusals"] = " ".join(f"{t:.2f}:{n}" for t, n in r.refusals)
    d["brake_on_object"] = " ".join(f"{k}={v:.2f}" for k, v in r.brake_on_object.items())
    d["selected_objects"] = " ".join(r.selected_objects)
    d["t_confirmed"] = " ".join(f"{k}={v:.2f}" for k, v in r.t_confirmed.items())
    for key in ("min_ttc_s", "min_gap_m"):
        if d[key] == float("inf"):
            d[key] = ""
    return d
